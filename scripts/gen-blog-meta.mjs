/**
 * Writes lib/blog-meta.ts: every article's card fields and nothing else.
 *
 * The in-app search index used to import BLOG_POSTS directly, which dragged
 * every article body (115 KB raw, 38 KB gzipped) into the search overlay's
 * lazy chunk — the one that loads when someone taps search in a crowded park.
 * Client code imports this slim file; server pages keep using lib/blog.ts.
 *
 * Runs before every build (package.json "build"), so it can't drift.
 */
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const { BLOG_POSTS, NEXT_STEP_POSTS } = await import("../lib/blog.ts");
const FIELDS = ["slug", "title", "description", "eyebrow", "emoji", "date", "readMins"];
const meta = BLOG_POSTS.map((p) => Object.fromEntries(FIELDS.map((f) => [f, p[f]])));
const out = `// GENERATED by scripts/gen-blog-meta.mjs from lib/blog.ts — do not edit.
// Card fields only, so client bundles never carry article bodies.
export type BlogMeta = { slug: string; title: string; description: string; eyebrow: string; emoji: string; date: string; readMins: number };

export const BLOG_META: BlogMeta[] = ${JSON.stringify(meta, null, 2)};

/** Slugs of the new-believer guides, in the order the first-steps screen lists them. */
export const NEXT_STEP_SLUGS: string[] = ${JSON.stringify([...NEXT_STEP_POSTS])};
`;
const target = fileURLToPath(new URL("../lib/blog-meta.ts", import.meta.url));
let current = "";
try { current = readFileSync(target, "utf8"); } catch { /* first run */ }
if (current !== out) {
  writeFileSync(target, out);
  console.log(`gen-blog-meta: wrote ${meta.length} articles to lib/blog-meta.ts`);
} else {
  console.log(`gen-blog-meta: lib/blog-meta.ts up to date (${meta.length} articles)`);
}
